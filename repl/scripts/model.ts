// Generate TypeScript types from the JSON schemas of Structure. Usage:
// node scripts/model.ts <schema directory> <output directory>

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix, sep } from "node:path";

type Json = null | boolean | number | string | Json[] | Schema;
type Schema = { [key: string]: Json };

// The type of the empty schema: any JSON value.
const JSON_FILE = `// Generated by scripts/model.ts. Do not edit.

// Any JSON value.
export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
`;

// Keywords that give the type of a value.
const SHAPES = new Set([
  "$ref",
  "type",
  "enum",
  "properties",
  "required",
  "additionalProperties",
  "patternProperties",
  "items",
  "anyOf",
  "oneOf",
  "definitions",
]);

// Keywords that only check or describe a value. A type can omit them.
const CHECKS = new Set([
  "$schema",
  "title",
  "description",
  "default",
  "format",
  "pattern",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "exclusiveMinimum",
  "exclusiveMaximum",
  "multipleOf",
  "minItems",
  "maxItems",
  "uniqueItems",
  "minProperties",
  "maxProperties",
  "not",
]);

// The schemas in a directory by path, for example base/args.schema.json
export function read(directory: string): Map<string, Schema> {
  const files = readdirSync(directory, { recursive: true, encoding: "utf8" })
    .filter((file) => file.endsWith(".schema.json"))
    .sort();
  return new Map(files.map((file) => [file.split(sep).join("/"), JSON.parse(readFileSync(join(directory, file), "utf8"))]));
}

// The TypeScript files of the schemas by path, for example base/args.ts
export function generate(schemas: Map<string, Schema>): Map<string, string> {
  const files = new Map([["json.ts", JSON_FILE]]);
  for (const path of schemas.keys()) {
    const file = path.replace(/\.schema\.json$/, ".ts");
    if (files.has(file)) {
      throw new Error(`${path}: the file ${file} already exists`);
    }
    files.set(file, new Module(path, schemas).toString());
  }
  return files;
}

// Replace the files in a directory.
export function write(directory: string, files: Map<string, string>) {
  rmSync(directory, { recursive: true, force: true });
  for (const [file, text] of files) {
    mkdirSync(dirname(join(directory, file)), { recursive: true });
    writeFileSync(join(directory, file), text);
  }
}

// The TypeScript module of one schema.
class Module {
  readonly #path: string;
  readonly #schemas: Map<string, Schema>;
  // The alias of each imported module, by schema path.
  readonly #imports = new Map<string, string>();
  #json = false;

  constructor(path: string, schemas: Map<string, Schema>) {
    this.#path = path;
    this.#schemas = schemas;
  }

  // The type of the schema, and a type for each of its definitions.
  toString(): string {
    const schema = this.#schemas.get(this.#path)!;
    const types = new Map<string, string>();
    const add = (name: string, schema: Json) => {
      if (types.has(name)) {
        throw new Error(`${this.#path}: the type ${name} already exists`);
      }
      types.set(name, `${comment(schema, "")}export type ${name} = ${this.#type(schema, "")};\n`);
    };
    // A schema with only definitions gives only their types.
    if (Object.keys(schema).some((key) => SHAPES.has(key) && key !== "definitions") || !schema.definitions) {
      add(typeName(this.#path), schema);
    }
    for (const [key, definition] of Object.entries(isSchema(schema.definitions) ? schema.definitions : {})) {
      add(pascal(key), definition);
    }
    const imports = [...this.#imports].map(
      ([path, alias]) => `import type * as ${alias} from "${this.#relative(path.replace(/\.schema\.json$/, ".ts"))}";\n`,
    );
    if (this.#json) {
      imports.unshift(`import type { Json } from "${this.#relative("json.ts")}";\n`);
    }
    const header = `// Generated from ${this.#path} by scripts/model.ts. Do not edit.\n\n`;
    return header + (imports.length ? imports.join("") + "\n" : "") + [...types.values()].join("\n");
  }

  #type(schema: Json, indent: string): string {
    if (!isSchema(schema)) {
      throw new Error(`${this.#path}: a schema is not an object: ${JSON.stringify(schema)}`);
    }
    for (const key of Object.keys(schema)) {
      if (!SHAPES.has(key) && !CHECKS.has(key)) {
        throw new Error(`${this.#path}: unknown keyword ${key}`);
      }
    }
    if (typeof schema.$ref === "string") {
      return this.#ref(schema.$ref);
    }
    if (Array.isArray(schema.enum)) {
      return union(schema.enum.map((value) => JSON.stringify(value)));
    }
    const types = [schema.type ?? []].flat();
    if (types.length === 0 && ["properties", "patternProperties", "additionalProperties"].some((key) => key in schema)) {
      types.push("object");
    } else if (types.length === 0 && "items" in schema) {
      types.push("array");
    }
    // Without a type of its own, a schema is one of its members.
    if (types.length === 0) {
      const members = [schema.anyOf ?? [], schema.oneOf ?? []].flat() as Json[];
      return members.length ? union(members.map((member) => this.#type(member, indent))) : this.#any();
    }
    return union(types.map((type) => this.#typeOf(type, schema, indent)));
  }

  #typeOf(type: Json, schema: Schema, indent: string): string {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const items = isSchema(schema.items) ? this.#type(schema.items, indent) : this.#any();
        return items.includes(" | ") ? `(${items})[]` : `${items}[]`;
      }
      case "object":
        return this.#object(schema, indent);
      default:
        throw new Error(`${this.#path}: unknown type ${JSON.stringify(type)}`);
    }
  }

  #object(schema: Schema, indent: string): string {
    const inner = `${indent}  `;
    const required = new Set(Array.isArray(schema.required) ? schema.required : []);
    const properties = Object.entries(isSchema(schema.properties) ? schema.properties : {}).map(([key, value]) => ({
      key,
      value,
      type: this.#type(value, inner),
      optional: !required.has(key),
    }));
    const lines = properties.map(
      ({ key, value, type, optional }) => `${comment(value, inner)}${inner}${property(key)}${optional ? "?" : ""}: ${type};`,
    );
    const index = Object.values(isSchema(schema.patternProperties) ? schema.patternProperties : {}).map((value) =>
      this.#type(value, inner),
    );
    if (isSchema(schema.additionalProperties)) {
      index.push(this.#type(schema.additionalProperties, inner));
    } else if (schema.additionalProperties !== false && properties.length === 0 && index.length === 0) {
      index.push(this.#any());
    } else if (properties.length === 0 && index.length === 0) {
      index.push("never");
    }
    // TypeScript requires each property type in the index type.
    if (index.length && properties.length) {
      index.push(...properties.map(({ type }) => type));
      if (properties.some(({ optional }) => optional)) {
        index.push("undefined");
      }
    }
    if (index.length) {
      lines.push(`${inner}[key: string]: ${union(index)};`);
    }
    return lines.length === 1 && !lines[0].includes("\n") && index.length && !properties.length
      ? `{ ${lines[0].trim().slice(0, -1)} }`
      : `{\n${lines.join("\n")}\n${indent}}`;
  }

  // The type at a $ref: a schema, or a definition of a schema.
  #ref(ref: string): string {
    const url = new URL(ref, `file:///${this.#path}`);
    const path = decodeURIComponent(url.pathname).slice(1);
    const pointer = decodeURIComponent(url.hash.slice(1));
    const definition = /^\/definitions\/([^/]+)$/.exec(pointer)?.[1];
    const schema = this.#schemas.get(path);
    const definitions = isSchema(schema?.definitions) ? schema.definitions : {};
    if (!schema || (pointer && !definition) || (definition && !isSchema(definitions[definition]))) {
      throw new Error(`${this.#path}: unknown $ref ${ref}`);
    }
    const name = definition ? pascal(definition) : typeName(path);
    if (path === this.#path) {
      return name;
    }
    if (!this.#imports.has(path)) {
      const base = `${typeName(path).replace(/^./, (first) => first.toLowerCase())}Schema`;
      const aliases = new Set(this.#imports.values());
      let alias = base;
      for (let number = 2; aliases.has(alias); number++) {
        alias = `${base}${number}`;
      }
      this.#imports.set(path, alias);
    }
    return `${this.#imports.get(path)}.${name}`;
  }

  #any(): string {
    this.#json = true;
    return "Json";
  }

  // A module path relative to this module, for an import.
  #relative(file: string): string {
    const path = posix.relative(posix.dirname(this.#path), file);
    return path.startsWith(".") ? path : `./${path}`;
  }
}

function isSchema(value: Json | undefined): value is Schema {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function union(types: string[]): string {
  return [...new Set(types)].join(" | ");
}

// The type name of a schema file, for example FindOneByName.
function typeName(path: string): string {
  return pascal(posix.basename(path, ".schema.json"));
}

function pascal(name: string): string {
  return name.replace(/(?:^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, first: string) => first.toUpperCase());
}

function property(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

// The description of a schema as a documentation comment.
function comment(schema: Json, indent: string): string {
  return isSchema(schema) && typeof schema.description === "string"
    ? `${indent}/** ${schema.description.replaceAll("*/", "*\\/")} */\n`
    : "";
}

if (import.meta.main) {
  const [schemas, output] = process.argv.slice(2);
  if (!schemas || !output) {
    console.error("Usage: node scripts/model.ts <schema directory> <output directory>");
    process.exit(1);
  }
  write(output, generate(read(schemas)));
}
